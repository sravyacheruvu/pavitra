export type DailyPooja = {
  dow: number;
  weekday: LangText;
  deity: Devotion;
  dayDeity: Devotion;
  personal: boolean;
  ishtaNote?: { name: LangText; weekday: LangText };
  steps: { title: LangText; detail: LangText }[];
};

/** Today's pooja, driven by the day of the week (deity, mantra and focus rotate daily). */
export function getDailyPooja(dow: number, ishta?: string, followed?: string[]): DailyPooja {
  const dayKey = DAY_DEITY[dow] ?? "vishnu";
  const deity = DEVOTIONS[dayKey] ?? DEVOTIONS.vishnu;
  const personal =
    (!!ishta && ishta === dayKey) || (!!followed && followed.includes(dayKey));
  const ishtaDeity = ishta && DEVOTIONS[ishta] ? DEVOTIONS[ishta] : undefined;
  const ishtaDayIdx = ishta ? DAY_DEITY.indexOf(ishta) : -1;
  const ishtaNote =
    ishtaDeity && ishtaDayIdx >= 0 && ishtaDayIdx !== dow
      ? { name: ishtaDeity.name, weekday: VAARA[ishtaDayIdx] }
      : undefined;
  return { dow, weekday: VAARA[dow] ?? VAARA[0], deity, dayDeity: deity, personal, ishtaNote, steps: QUICK_STEPS };
}
