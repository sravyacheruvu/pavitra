/**
 * enumerations.ts — reusable, detailed liturgical lists (named leaves, the
 * forms of the Goddess, the six tastes, and — as they are sourced — the full
 * Ashtottara Shatanamavali / Sahasranama recitations).
 *
 * A vidhi step references one of these by key via `detailsRef`, and the guided
 * display renders the full list so the user can actually perform (and recite)
 * the step rather than read an instruction about it.
 *
 * NOTE: sacred texts vary by sampradaya and family tradition. These are the
 * standard South-Indian lists; please verify against your family or priest's
 * text before ritual use.
 */
import type { LangText } from "../i18n";

export type NamaItem = {
  /** 1-based index for display. */
  n: number;
  /** Sanskrit in Devanagari (e.g. "ॐ सुमुखाय नमः"). Optional for plain lists. */
  sa?: string;
  /** Transliteration (e.g. "Om Sumukhaya Namah"). */
  tr: string;
  /** Optional short gloss (the leaf, the taste's meaning, etc.). */
  en?: string;
};

export type Enumeration = {
  label: LangText;
  /** namavali = recited names; list = a named/ordered list with glosses. */
  kind: "namavali" | "list";
  intro?: LangText;
  items: NamaItem[];
};

/** Helper to number a list of items written without explicit indices. */
const numbered = (rows: Omit<NamaItem, "n">[]): NamaItem[] =>
  rows.map((r, i) => ({ n: i + 1, ...r }));

